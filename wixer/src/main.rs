#[derive(Parser)]
#[command(name = "wixer")]
#[command(about = "WiX Installer Toolkit", long_about = None)]
struct Cli {
    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand)]
enum Commands {
    /// Convert XSD schemas to JSON Schema
    XsdToJson {
        /// Input XSD file path or URL
        #[arg(short, long)]
        input: Option<String>,

        /// Output JSON Schema file
        #[arg(short, long)]
        output: Option<String>,

        /// Download all WiX v4 schemas from GitHub
        #[arg(long)]
        download_wix: bool,

        /// Directory for downloaded schemas
        #[arg(long, default_value = "schemas")]
        schema_dir: PathBuf,

        /// Directory for generated JSON schemas
        #[arg(long, default_value = "json-schemas")]
        output_dir: PathBuf,

        /// How to handle XML attributes
        #[arg(long, value_enum, default_value_t = AttributeStrategy::Inline)]
        attribute_strategy: AttributeStrategy,

        /// Exclude descriptions from schemas
        #[arg(long)]
        no_descriptions: bool,

        /// Enable strict mode (enforce required fields)
        #[arg(long)]
        strict: bool,

        /// Root element name for schema
        #[arg(long)]
        root_element: Option<String>,
    },
    /// Convert YAML to WiX XML
    YamlToWix {
        /// Input YAML file
        #[arg(index = 1)]
        input: Option<PathBuf>,

        /// Output WiX XML file
        #[arg(index = 2)]
        output: Option<PathBuf>,

        /// Input directory containing YAML files
        #[arg(long)]
        input_dir: Option<PathBuf>,

        /// Output directory for WiX XML files
        #[arg(long)]
        output_dir: Option<PathBuf>,

        /// Attribute handling strategy (must match XSD conversion)
        #[arg(long, value_enum, default_value_t = AttributeStrategy::Inline)]
        attribute_strategy: AttributeStrategy,

        /// Path to known_attributes.json (generated by xsd-to-json)
        #[arg(long)]
        attributes_file: Option<PathBuf>,
    },
    /// Convert WiX XML to YAML
    WixToYaml {
        /// Input WiX XML file
        #[arg(index = 1)]
        input: PathBuf,

        /// Output YAML file
        #[arg(index = 2)]
        output: PathBuf,

        /// Attribute handling strategy
        #[arg(long, value_enum, default_value_t = AttributeStrategy::Inline)]
        attribute_strategy: AttributeStrategy,
    },
    /// Validate YAML against JSON Schema
    Validate {
        /// JSON Schema file
        #[arg(index = 1)]
        schema: Option<PathBuf>,

        /// YAML file to validate
        #[arg(index = 2)]
        yaml: Option<PathBuf>,

        /// Directory containing JSON schemas
        #[arg(long)]
        schema_dir: Option<PathBuf>,

        /// Directory containing YAML files to validate
        #[arg(long)]
        yaml_dir: Option<PathBuf>,
    },
    /// Initialize wixer by downloading XSD schemas to a local cache
    Init {
        /// Delete existing cache and re-download schemas
        #[arg(long)]
        fresh: bool,
    },
    /// Recursively import WiX files from a directory
    Import {
        /// Input directory containing .wxs or .wxs.in files
        #[arg(index = 1)]
        input_dir: PathBuf,

        /// Output directory for .yaml files
        #[arg(index = 2)]
        output_dir: PathBuf,

        /// Attribute handling strategy
        #[arg(long, value_enum, default_value_t = AttributeStrategy::Inline)]
        attribute_strategy: AttributeStrategy,
    },
    /// Recursively export YAML files to WiX XML
    Export {
        /// Input directory containing .wys, .wyi, .wyl files
        #[arg(index = 1)]
        input_dir: PathBuf,

        /// Output directory for WiX files
        #[arg(index = 2)]
        output_dir: PathBuf,

        /// Attribute handling strategy
        #[arg(long, value_enum, default_value_t = AttributeStrategy::Inline)]
        attribute_strategy: AttributeStrategy,
    },
    /// Describe WiX properties, variables, and concepts
    Describe {
        /// Search term (e.g. "ProductName", "INSTALLFOLDER")
        #[arg(index = 1)]
        term: String,
    },
    /// Wrapper around 'wix build' that transparently converts YAML files
    #[command(external_subcommand)]
    Build(Vec<String>),
    /// Generate documentation from XSD schemas
    Doc {
        /// Output directory for documentation
        #[arg(long, default_value = "wix_docs")]
        output_dir: PathBuf,

        /// Format to generate (markdown, html, or all)
        #[arg(long, default_value = "markdown")]
        format: String,
    },
    /// Start the WiX Language Server
    Lsp,
    /// Map WiX schemas to MSIX schemas
    MapSchemas,
    /// Migrate WiX project to another format
    Migrate {
        /// Input WiX file
        #[arg(index = 1)]
        input: PathBuf,

        /// Output directory
        #[arg(index = 2)]
        output_dir: PathBuf,

        /// Migration target
        #[arg(long, value_enum)]
        target: commands::migrate::MigrationTarget,
    },
    /// Upgrade WiX v3 files to v4/v6
    Upgrade {
        /// Input file
        #[arg(index = 1)]
        input: PathBuf,

        /// Output file
        #[arg(index = 2)]
        output: Option<PathBuf>,
    },
    /// Inspect WiX PDB file
    InspectPdb {
        /// Path to .wixpdb file
        #[arg(index = 1)]
        path: PathBuf,

        /// Symbol ID to lookup
        #[arg(long)]
        symbol: Option<String>,
    },
    /// Visualize execution sequence
    Sequence {
        /// Path to .wixpdb file
        #[arg(index = 1)]
        path: PathBuf,

        /// Filter by table name (e.g. InstallExecuteSequence)
        #[arg(long)]
        table: Option<String>,
    },
}

#[tokio::main]
async fn main() {
    // Load config early for logging setup
    let config = WixerConfig::load();
    
    let mut layers = Vec::new();

    // Stderr layer (default)
    let stderr_layer = fmt::layer()
        .with_writer(std::io::stderr)
        .with_filter(tracing_subscriber::filter::LevelFilter::INFO)
        .boxed();
    layers.push(stderr_layer);

    // File layer (if configured)
    if let Some(log_file) = &config.logging.file {
        if let Ok(file) = std::fs::File::create(log_file) {
            let file_layer = fmt::layer()
                .with_writer(file)
                .with_ansi(false)
                .with_filter(tracing_subscriber::filter::LevelFilter::DEBUG)
                .boxed();
            layers.push(file_layer);
        } else {
            eprintln!("Failed to create log file: {}", log_file);
        }
    }

    tracing_subscriber::registry()
        .with(layers)
        .init();

    // Impersonation Check
    if let Ok(exe) = std::env::current_exe()
        && let Some(name) = exe.file_stem()
            && name.to_string_lossy().eq_ignore_ascii_case("wix") {
                // We are running as wix.exe
                let args: Vec<String> = std::env::args().skip(1).collect();
                if !args.is_empty() {
                    let cmd = &args[0];
                    let wixer_cmds = [
                        "xsd-to-json", "yaml-to-wix", "wix-to-yaml", "validate", "init",
                        "import", "export", "describe", "doc", "lsp", "map-schemas",
                        "migrate", "upgrade", "build" // build is handled by commands::build::run anyway, but listed here
                    ];
                    
                    // If it is NOT a wixer command, treat as passthrough/build wrapper immediately
                    // But wait, 'build' is a wixer command (wrapper).
                    // If it IS 'build', we can let clap handle it OR pass to build::run directly.
                    // Passing to build::run directly avoids Clap parsing issues if wix build arguments conflict with wixer options?
                    // But wixer build command is `Build(Vec<String>)` (external_subcommand), so it captures everything.
                    
                    // The only issue is unknown commands like 'msi'.
                    if !wixer_cmds.contains(&cmd.as_str()) {
                        // Passthrough
                        if let Err(e) = commands::build::run(args) {
                            error!("Error running wix wrapper: {}", e);
                            std::process::exit(1);
                        }
                        return;
                    }
                }
            }

    let cli = Cli::parse();

    match &cli.command {
        Commands::XsdToJson {
            input,
            output,
            download_wix,
            schema_dir,
            output_dir,
            attribute_strategy,
            no_descriptions,
            strict,
            root_element,
        } => {
            let mut all_attributes = HashSet::new();

            if *download_wix {
                match xsd_to_json::download_wix_schemas(schema_dir, false).await {
                    Ok(files) => {
                        for file in files {
                            match xsd_to_json::convert_xsd(
                                file.to_str().unwrap(),
                                None,
                                output_dir,
                                *attribute_strategy,
                                !*no_descriptions,
                                *strict,
                                root_element.as_deref(),
                            ) {
                                Ok(attrs) => all_attributes.extend(attrs),
                                Err(e) => error!(file = %file.display(), "Error converting: {}", e),
                            }
                        }
                    }
                    Err(e) => {
                        error!("Error downloading schemas: {}", e);
                        std::process::exit(1);
                    }
                }
            } else if input.is_none() {
                error!("Either --input or --download-wix is required");
                std::process::exit(1);
            }

            if let Some(input_path) = input {
                match xsd_to_json::convert_xsd(
                    input_path,
                    output.as_deref(),
                    output_dir,
                    *attribute_strategy,
                    !*no_descriptions,
                    *strict,
                    root_element.as_deref(),
                ) {
                    Ok(attrs) => all_attributes.extend(attrs),
                    Err(e) => {
                        error!("Error converting XSD: {}", e);
                        std::process::exit(1);
                    }
                }
            }

            // Save known attributes
            if !all_attributes.is_empty() {
                let sorted_attributes: BTreeSet<_> = all_attributes.into_iter().collect();
                let attr_file = output_dir.join("known_attributes.json");
                let file =
                    File::create(&attr_file).expect("Failed to create known_attributes.json");
                let writer = BufWriter::new(file);
                serde_json::to_writer_pretty(writer, &sorted_attributes)
                    .expect("Failed to write attributes");
                info!("Generated attribute list: {}", attr_file.display());
            }
        }
        Commands::YamlToWix {
            input,
            output,
            input_dir,
            output_dir,
            attribute_strategy,
            attributes_file,
        } => {
            // Load known attributes
            let mut known_attributes = HashSet::new();
            let attr_path = if let Some(p) = attributes_file {
                Some(p.clone())
            } else if PathBuf::from("json-schemas/known_attributes.json").exists() {
                Some(PathBuf::from("json-schemas/known_attributes.json"))
            } else if let Ok(root) = find_wixer_root() {
                let path = root
                    .join("cache")
                    .join("json-schema")
                    .join("known_attributes.json");
                if path.exists() { Some(path) } else { None }
            } else {
                None
            };

            if let Some(path) = attr_path {
                if let Ok(file) = File::open(&path) {
                    let reader = BufReader::new(file);
                    match serde_json::from_reader(reader) {
                        Ok(attrs) => known_attributes = attrs,
                        Err(e) => warn!(
                            file = %path.display(),
                            "Failed to parse attributes file: {}",
                            e
                        ),
                    }
                } else {
                    warn!(file = %path.display(), "Failed to open attributes file");
                }
            } else if *attribute_strategy == AttributeStrategy::Inline {
                warn!(
                    "No known_attributes.json found and strategy is Inline. Attribute detection may fail."
                );
            }

            if let (Some(in_dir), Some(out_dir)) = (input_dir, output_dir) {
                if let Err(e) = yaml_to_wix::convert_directory(
                    in_dir,
                    out_dir,
                    *attribute_strategy,
                    &known_attributes,
                ) {
                    error!("Error converting directory: {}", e);
                    std::process::exit(1);
                }
            } else if let (Some(input_path), Some(output_path)) = (input, output) {
                if let Err(e) = yaml_to_wix::convert_file(
                    input_path,
                    output_path,
                    *attribute_strategy,
                    &known_attributes,
                ) {
                    error!("Error converting file: {}", e);
                    std::process::exit(1);
                }
            } else {
                error!(
                    "Either provide input and output files, or use --input-dir and --output-dir"
                );
                std::process::exit(1);
            }
        }
        Commands::WixToYaml {
            input,
            output,
            attribute_strategy,
        } => {
            let known_attributes = HashSet::new(); // TODO: Load if needed, but import is looser
            if let Err(e) =
                wix_to_yaml::convert_file(input, output, *attribute_strategy, &known_attributes)
            {
                error!("Error converting WiX to YAML: {}", e);
                std::process::exit(1);
            }
        }
        Commands::Validate {
            schema,
            yaml,
            schema_dir,
            yaml_dir,
        } => {
            if let (Some(s_dir), Some(y_dir)) = (schema_dir, yaml_dir) {
                if let Err(e) = validate::validate_directory(s_dir, y_dir) {
                    error!("Error validating directory: {}", e);
                    std::process::exit(1);
                }
            } else if let (Some(schema_path), Some(yaml_path)) = (schema, yaml) {
                if let Err(e) = validate::validate_file(schema_path, yaml_path) {
                    error!("Validation failed: {}", e);
                    std::process::exit(1);
                }
            } else {
                error!("Either provide schema and yaml files, or use --schema-dir and --yaml-dir");
                std::process::exit(1);
            }
        }
        Commands::Init { fresh } => {
            if let Err(e) = commands::init::run(*fresh).await {
                error!("Error running init: {}", e);
                std::process::exit(1);
            }
        }
        Commands::Import {
            input_dir,
            output_dir,
            attribute_strategy,
        } => {
            if let Err(e) = commands::import::run(input_dir, output_dir, *attribute_strategy) {
                error!("Error running import: {}", e);
                std::process::exit(1);
            }
        }
        Commands::Export {
            input_dir,
            output_dir,
            attribute_strategy,
        } => {
            if let Err(e) = commands::export::run(input_dir, output_dir, *attribute_strategy) {
                error!("Error running export: {}", e);
                std::process::exit(1);
            }
        }
        Commands::Describe { term } => {
            if let Err(e) = commands::describe::run(term.clone()) {
                error!("Error running describe: {}", e);
                std::process::exit(1);
            }
        }
        Commands::Build(args) => {
            if let Err(e) = commands::build::run(args.clone()) {
                error!("Error running build: {}", e);
                std::process::exit(1);
            }
        }
        Commands::Doc { output_dir, format } => {
            if let Err(e) = commands::doc::run(output_dir, format) {
                error!("Error generating documentation: {}", e);
                std::process::exit(1);
            }
        }
        Commands::Lsp => {
            if let Err(e) = commands::lsp::run().await {
                error!("Error running LSP: {}", e);
                std::process::exit(1);
            }
        }
        Commands::MapSchemas => {
            if let Err(e) = commands::map_schemas::run() {
                error!("Error mapping schemas: {}", e);
                std::process::exit(1);
            }
        }
        Commands::Migrate {
            input,
            output_dir,
            target,
        } => {
            if let Err(e) =
                commands::migrate::run(input.clone(), output_dir.clone(), target.clone())
            {
                error!("Error migrating: {}", e);
                std::process::exit(1);
            }
        }
        Commands::Upgrade { input, output } => {
            if let Err(e) = commands::upgrade::run(input.clone(), output.clone()) {
                error!("Error upgrading: {}", e);
                std::process::exit(1);
            }
        }
        Commands::InspectPdb { path, symbol } => {
            if let Err(e) = commands::pdb::run(path, symbol.clone()) {
                error!("Error inspecting PDB: {}", e);
                std::process::exit(1);
            }
        }
        Commands::Sequence { path, table } => {
            if let Err(e) = commands::sequence::run(path, table.clone()) {
                error!("Error visualizing sequence: {}", e);
                std::process::exit(1);
            }
        }
    }
}
