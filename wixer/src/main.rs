use clap::{Parser, Subcommand, ValueEnum};
use std::collections::{BTreeSet, HashSet};
use std::env;
use std::fs::File;
use std::io::{BufReader, BufWriter};
use std::path::PathBuf;

mod validate;
mod xsd_to_json;
mod yaml_to_wix;

#[derive(Parser)]
#[command(name = "wixer")]
#[command(about = "WiX Installer Toolkit", long_about = None)]
struct Cli {
    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand)]
enum Commands {
    /// Convert XSD schemas to JSON Schema
    XsdToJson {
        /// Input XSD file path or URL
        #[arg(short, long)]
        input: Option<String>,

        /// Output JSON Schema file
        #[arg(short, long)]
        output: Option<String>,

        /// Download all WiX v4 schemas from GitHub
        #[arg(long)]
        download_wix: bool,

        /// Directory for downloaded schemas
        #[arg(long, default_value = "schemas")]
        schema_dir: PathBuf,

        /// Directory for generated JSON schemas
        #[arg(long, default_value = "json-schemas")]
        output_dir: PathBuf,

        /// How to handle XML attributes
        #[arg(long, value_enum, default_value_t = AttributeStrategy::Inline)]
        attribute_strategy: AttributeStrategy,

        /// Exclude descriptions from schemas
        #[arg(long)]
        no_descriptions: bool,

        /// Enable strict mode (enforce required fields)
        #[arg(long)]
        strict: bool,

        /// Root element name for schema
        #[arg(long)]
        root_element: Option<String>,
    },
    /// Convert YAML to WiX XML
    YamlToWix {
        /// Input YAML file
        #[arg(index = 1)]
        input: Option<PathBuf>,

        /// Output WiX XML file
        #[arg(index = 2)]
        output: Option<PathBuf>,

        /// Input directory containing YAML files
        #[arg(long)]
        input_dir: Option<PathBuf>,

        /// Output directory for WiX XML files
        #[arg(long)]
        output_dir: Option<PathBuf>,

        /// Attribute handling strategy (must match XSD conversion)
        #[arg(long, value_enum, default_value_t = AttributeStrategy::Inline)]
        attribute_strategy: AttributeStrategy,

        /// Path to known_attributes.json (generated by xsd-to-json)
        #[arg(long)]
        attributes_file: Option<PathBuf>,
    },
    /// Validate YAML against JSON Schema
    Validate {
        /// JSON Schema file
        #[arg(index = 1)]
        schema: Option<PathBuf>,

        /// YAML file to validate
        #[arg(index = 2)]
        yaml: Option<PathBuf>,

        /// Directory containing JSON schemas
        #[arg(long)]
        schema_dir: Option<PathBuf>,

        /// Directory containing YAML files to validate
        #[arg(long)]
        yaml_dir: Option<PathBuf>,
    },
    /// Initialize wixer by downloading XSD schemas to a local cache
    Init {
        /// Delete existing cache and re-download schemas
        #[arg(long)]
        fresh: bool,
    },
    /// Wrapper around 'wix build' that transparently converts YAML files
    #[command(external_subcommand)]
    Build(Vec<String>),
}

#[derive(Copy, Clone, PartialEq, Eq, PartialOrd, Ord, ValueEnum, Debug)]
pub enum AttributeStrategy {
    Inline,
    Prefix,
    Separate,
}

fn main() {
    let cli = Cli::parse();

    match &cli.command {
        Commands::XsdToJson {
            input,
            output,
            download_wix,
            schema_dir,
            output_dir,
            attribute_strategy,
            no_descriptions,
            strict,
            root_element,
        } => {
            let mut all_attributes = HashSet::new();

            if *download_wix {
                match xsd_to_json::download_wix_schemas(schema_dir, false) {
                    Ok(files) => {
                        for file in files {
                            match xsd_to_json::convert_xsd(
                                file.to_str().unwrap(),
                                None,
                                output_dir,
                                *attribute_strategy,
                                !*no_descriptions,
                                *strict,
                                root_element.as_deref(),
                            ) {
                                Ok(attrs) => all_attributes.extend(attrs),
                                Err(e) => eprintln!("Error converting {}: {}", file.display(), e),
                            }
                        }
                    }
                    Err(e) => {
                        eprintln!("Error downloading schemas: {}", e);
                        std::process::exit(1);
                    }
                }
            } else if input.is_none() {
                eprintln!("Either --input or --download-wix is required");
                std::process::exit(1);
            }

            if let Some(input_path) = input {
                match xsd_to_json::convert_xsd(
                    input_path,
                    output.as_deref(),
                    output_dir,
                    *attribute_strategy,
                    !*no_descriptions,
                    *strict,
                    root_element.as_deref(),
                ) {
                    Ok(attrs) => all_attributes.extend(attrs),
                    Err(e) => {
                        eprintln!("Error converting XSD: {}", e);
                        std::process::exit(1);
                    }
                }
            }

            // Save known attributes
            if !all_attributes.is_empty() {
                let sorted_attributes: BTreeSet<_> = all_attributes.into_iter().collect();
                let attr_file = output_dir.join("known_attributes.json");
                let file =
                    File::create(&attr_file).expect("Failed to create known_attributes.json");
                let writer = BufWriter::new(file);
                serde_json::to_writer_pretty(writer, &sorted_attributes)
                    .expect("Failed to write attributes");
                println!("✓ Generated attribute list: {}", attr_file.display());
            }
        }
        Commands::YamlToWix {
            input,
            output,
            input_dir,
            output_dir,
            attribute_strategy,
            attributes_file,
        } => {
            // Load known attributes
            let mut known_attributes = HashSet::new();
            let attr_path = if let Some(p) = attributes_file {
                Some(p.clone())
            } else if PathBuf::from("json-schemas/known_attributes.json").exists() {
                Some(PathBuf::from("json-schemas/known_attributes.json"))
            } else if let Ok(root) = find_wixer_root() {
                let path = root
                    .join("cache")
                    .join("json-schema")
                    .join("known_attributes.json");
                if path.exists() { Some(path) } else { None }
            } else {
                None
            };

            if let Some(path) = attr_path {
                if let Ok(file) = File::open(&path) {
                    let reader = BufReader::new(file);
                    match serde_json::from_reader(reader) {
                        Ok(attrs) => known_attributes = attrs,
                        Err(e) => eprintln!(
                            "Warning: Failed to parse attributes file {}: {}",
                            path.display(),
                            e
                        ),
                    }
                } else {
                    eprintln!("Warning: Failed to open attributes file {}", path.display());
                }
            } else if *attribute_strategy == AttributeStrategy::Inline {
                eprintln!(
                    "Warning: No known_attributes.json found and strategy is Inline. Attribute detection may fail."
                );
            }

            if let (Some(in_dir), Some(out_dir)) = (input_dir, output_dir) {
                if let Err(e) = yaml_to_wix::convert_directory(
                    in_dir,
                    out_dir,
                    *attribute_strategy,
                    &known_attributes,
                ) {
                    eprintln!("Error converting directory: {}", e);
                    std::process::exit(1);
                }
            } else if let (Some(input_path), Some(output_path)) = (input, output) {
                if let Err(e) = yaml_to_wix::convert_file(
                    input_path,
                    output_path,
                    *attribute_strategy,
                    &known_attributes,
                ) {
                    eprintln!("Error converting file: {}", e);
                    std::process::exit(1);
                }
            } else {
                eprintln!(
                    "Either provide input and output files, or use --input-dir and --output-dir"
                );
                std::process::exit(1);
            }
        }
        Commands::Validate {
            schema,
            yaml,
            schema_dir,
            yaml_dir,
        } => {
            if let (Some(s_dir), Some(y_dir)) = (schema_dir, yaml_dir) {
                if let Err(e) = validate::validate_directory(s_dir, y_dir) {
                    eprintln!("Error validating directory: {}", e);
                    std::process::exit(1);
                }
            } else if let (Some(schema_path), Some(yaml_path)) = (schema, yaml) {
                if let Err(e) = validate::validate_file(schema_path, yaml_path) {
                    eprintln!("Validation failed: {}", e);
                    std::process::exit(1);
                }
            } else {
                eprintln!(
                    "Either provide schema and yaml files, or use --schema-dir and --yaml-dir"
                );
                std::process::exit(1);
            }
        }
        Commands::Init { fresh } => {
            let wixer_root = find_wixer_root().unwrap_or_else(|e| {
                eprintln!("Error determining project root: {}", e);
                std::process::exit(1);
            });

            let cache_base = wixer_root.join("cache");
            let xml_schema_dir = cache_base.join("xml-schema");
            let json_schema_dir = cache_base.join("json-schema");
            println!("Initializing wixer in {}", wixer_root.display());

            if *fresh {
                if cache_base.exists() {
                    println!("Clearing cache...");
                    if let Err(e) = std::fs::remove_dir_all(&cache_base) {
                        eprintln!("Error clearing cache: {}", e);
                        std::process::exit(1);
                    }
                }
            }

            match xsd_to_json::download_wix_schemas(&xml_schema_dir, *fresh) {
                Ok(files) => {
                    let mut all_attributes = HashSet::new();
                    println!("Generating JSON schemas...");

                    for file in files {
                        match xsd_to_json::convert_xsd(
                            file.to_str().unwrap(),
                            None,
                            &json_schema_dir,
                            AttributeStrategy::Inline,
                            true,  // include_descriptions
                            false, // strict_mode
                            None,  // root_element
                        ) {
                            Ok(attrs) => all_attributes.extend(attrs),
                            Err(e) => eprintln!("Error converting {}: {}", file.display(), e),
                        }
                    }

                    // Save known attributes
                    if !all_attributes.is_empty() {
                        let sorted_attributes: BTreeSet<_> = all_attributes.into_iter().collect();
                        let attr_file = json_schema_dir.join("known_attributes.json");
                        let file = File::create(&attr_file)
                            .expect("Failed to create known_attributes.json");
                        let writer = BufWriter::new(file);
                        serde_json::to_writer_pretty(writer, &sorted_attributes)
                            .expect("Failed to write attributes");
                        println!("✓ Generated attribute list: {}", attr_file.display());
                    }

                    println!("✓ Initialization complete");
                }
                Err(e) => {
                    eprintln!("Error initializing: {}", e);
                    std::process::exit(1);
                }
            }
        }
        Commands::Build(args) => {
            if args.is_empty() {
                eprintln!("No arguments provided for build");
                std::process::exit(1);
            }

            // Check if it's actually the 'build' command
            if args[0] != "build" {
                // Pass through other commands to wix
                let status = std::process::Command::new("wix")
                    .args(args)
                    .status()
                    .unwrap_or_else(|e| {
                        eprintln!("Failed to execute wix: {}", e);
                        std::process::exit(1);
                    });
                std::process::exit(status.code().unwrap_or(1));
            }

            // It is 'build', let's intercept inputs
            let wixer_root = find_wixer_root().unwrap_or_else(|_| {
                // Fallback if not in a wixer project, use temp dir
                std::env::temp_dir().join("wixer_intermediates")
            });

            let intermediates_dir = wixer_root.join("intermediates");
            if !intermediates_dir.exists() {
                std::fs::create_dir_all(&intermediates_dir)
                    .expect("Failed to create intermediates dir");
            }

            // Load known attributes
            let mut known_attributes = HashSet::new();
            if let Ok(root) = find_wixer_root() {
                let path = root
                    .join("cache")
                    .join("json-schema")
                    .join("known_attributes.json");
                if path.exists() {
                    if let Ok(file) = File::open(&path) {
                        let reader = BufReader::new(file);
                        if let Ok(attrs) = serde_json::from_reader(reader) {
                            known_attributes = attrs;
                        }
                    }
                }
            }

            let mut new_args = Vec::new();
            new_args.push("build".to_string());

            for arg in &args[1..] {
                let path = PathBuf::from(arg);
                let is_yaml = path
                    .extension()
                    .map_or(false, |ext| ext == "yaml" || ext == "yml");

                if is_yaml && path.exists() {
                    // Check content for Wix root
                    if let Ok(content) = std::fs::read_to_string(&path) {
                        if content.contains("Wix:") || content.contains("Wix") {
                            // Simple check, parsed later
                            // Convert
                            let filename = path.file_stem().unwrap().to_string_lossy();
                            let output_path = intermediates_dir.join(format!("{}.wxs", filename));

                            match yaml_to_wix::convert_file(
                                &path,
                                &output_path,
                                AttributeStrategy::Inline,
                                &known_attributes,
                            ) {
                                Ok(_) => {
                                    new_args.push(output_path.to_string_lossy().to_string());
                                    continue;
                                }
                                Err(e) => {
                                    eprintln!("Failed to convert {}: {}", path.display(), e);
                                    // Fallback to original arg? Or fail?
                                    // Fail is safer
                                    std::process::exit(1);
                                }
                            }
                        }
                    }
                }
                new_args.push(arg.clone());
            }

            println!("Running: wix {}", new_args.join(" "));
            let status = std::process::Command::new("wix")
                .args(&new_args[1..]) // Skip "build" as it is in new_args[0] but we ran "wix"
                .status()
                .unwrap_or_else(|e| {
                    eprintln!("Failed to execute wix: {}", e);
                    std::process::exit(1);
                });
            std::process::exit(status.code().unwrap_or(1));
        }
    }
}

fn find_wixer_root() -> std::io::Result<PathBuf> {
    let current_dir = env::current_dir()?;
    let mut dir = current_dir.as_path();

    loop {
        let wixer_dir = dir.join(".wixer");
        if wixer_dir.exists() && wixer_dir.is_dir() {
            return Ok(wixer_dir);
        }

        if let Some(parent) = dir.parent() {
            dir = parent;
        } else {
            break;
        }
    }

    Ok(current_dir.join(".wixer"))
}
