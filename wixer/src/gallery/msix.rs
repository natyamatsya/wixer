enum MsixResult {
    Success,
    Skipped(String),
    Error(String),
}

fn get_msix_xml_dir(example: &BuildExample, msix_dir: &Path) -> Result<PathBuf> {
    // Use a sibling folder to msix/ so the msix output stays clean.
    let output_root = msix_dir
        .parent()
        .ok_or_else(|| anyhow::anyhow!("msix_dir has no parent"))?;
    Ok(output_root.join(".msix-tmp").join(&example.name))
}

fn export_yaml_to_xml_dir(
    source_dir: &Path,
    xml_dir: &Path,
    wixer_path: &Path,
    verbose: bool,
) -> Result<()> {
    if xml_dir.exists() {
        let _ = fs::remove_dir_all(xml_dir);
    }
    fs::create_dir_all(xml_dir)?;

    let mut cmd = Command::new(wixer_path);
    cmd.current_dir(source_dir);
    cmd.args(["export", "."]);
    cmd.arg(xml_dir);

    if verbose {
        eprintln!("  Running: {:?}", cmd);
    }

    let output = cmd.output()?;
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        let stdout = String::from_utf8_lossy(&output.stdout);
        anyhow::bail!(
            "{}",
            format!("{}\n{}", stderr, stdout)
                .lines()
                .next()
                .unwrap_or("export failed")
        );
    }

    Ok(())
}

fn yaml_to_xml_main_file(xml_dir: &Path, yaml_input: &Path) -> Result<PathBuf> {
    let file_name = yaml_input
        .file_name()
        .ok_or_else(|| anyhow::anyhow!("missing filename"))?
        .to_string_lossy();

    let xml_name = file_name.replace(".yaml", "");
    let xml_path = xml_dir.join(xml_name);
    if !xml_path.exists() {
        anyhow::bail!("missing exported XML file: {}", xml_path.display());
    }
    Ok(xml_path)
}

fn is_makeappx_available() -> bool {
    Command::new("MakeAppx").arg("/?").output().is_ok()
}

fn validate_msix_outputs(msix_dir: &Path, makeappx_available: bool) -> Result<usize> {
    let mut errors = 0usize;

    let entries: Vec<_> = match fs::read_dir(msix_dir) {
        Ok(it) => it.filter_map(|e| e.ok()).map(|e| e.path()).collect(),
        Err(_) => return Ok(0),
    };

    for example_dir in entries {
        if !example_dir.is_dir() {
            continue;
        }

        let example_name = example_dir
            .file_name()
            .map(|n| n.to_string_lossy().to_string())
            .unwrap_or_else(|| example_dir.display().to_string());

        // Level 1: XML well-formed + required fields.
        match validate_msix_manifest_level1(&example_dir) {
            Ok(()) => {
                println!("MSIX validate (L1) {}... ✓", example_name);
            }
            Err(e) => {
                errors += 1;
                println!("MSIX validate (L1) {}... ✗ ({})", example_name, e);
                continue;
            }
        }

        // Level 2: Try MakeAppx pack if available.
        if !makeappx_available {
            println!(
                "MSIX validate (L2) {}... ⊘ (MakeAppx not found)",
                example_name
            );
            continue;
        }

        match validate_msix_manifest_level2_makeappx(&example_dir) {
            Ok(()) => println!("MSIX validate (L2) {}... ✓", example_name),
            Err(e) => {
                errors += 1;
                println!("MSIX validate (L2) {}... ✗ ({})", example_name, e);
            }
        }
    }

    Ok(errors)
}

fn validate_msix_manifest_level1(example_dir: &Path) -> Result<()> {
    // Generated by `wixer migrate --target msix`
    let manifest = example_dir.join("AppxManifest.xml");
    let content = fs::read_to_string(&manifest)?;

    let mut reader = Reader::from_str(&content);
    reader.config_mut().trim_text(true);

    let mut buf = Vec::new();

    let mut has_package = false;
    let mut has_identity = false;
    let mut has_application = false;

    loop {
        match reader.read_event_into(&mut buf) {
            Ok(Event::Start(e)) | Ok(Event::Empty(e)) => {
                let qname = e.name();
                let name = qname.as_ref();
                // Ignore namespaces for validation.
                let local_name = name.split(|b| *b == b':').next_back().unwrap_or(name);

                if local_name == b"Package" {
                    has_package = true;
                }

                if local_name == b"Identity" {
                    // Require the usual identity attrs.
                    let mut has_name = false;
                    let mut has_publisher = false;
                    let mut has_version = false;
                    let mut has_arch = false;
                    for attr in e.attributes().flatten() {
                        match attr.key.as_ref() {
                            b"Name" => has_name = true,
                            b"Publisher" => has_publisher = true,
                            b"Version" => has_version = true,
                            b"ProcessorArchitecture" => has_arch = true,
                            _ => {}
                        }
                    }
                    if has_name && has_publisher && has_version && has_arch {
                        has_identity = true;
                    }
                }

                if local_name == b"Application" {
                    // Require at least Id + Executable.
                    let mut has_id = false;
                    let mut has_exe = false;
                    for attr in e.attributes().flatten() {
                        match attr.key.as_ref() {
                            b"Id" => has_id = true,
                            b"Executable" => has_exe = true,
                            _ => {}
                        }
                    }
                    if has_id && has_exe {
                        has_application = true;
                    }
                }
            }
            Ok(Event::Eof) => break,
            Err(e) => anyhow::bail!("invalid XML: {}", e),
            _ => {}
        }

        buf.clear();
    }

    if !has_package {
        anyhow::bail!("missing <Package>");
    }
    if !has_identity {
        anyhow::bail!("missing/invalid <Identity>");
    }
    if !has_application {
        anyhow::bail!("missing/invalid <Application>");
    }

    Ok(())
}

fn validate_msix_manifest_level2_makeappx(example_dir: &Path) -> Result<()> {
    let out = example_dir.join("__validate.msix");

    prepare_makeappx_staging(example_dir)?;

    let output = Command::new("MakeAppx")
        .args([
            "pack",
            "/d",
            example_dir.to_str().unwrap_or_default(),
            "/p",
            out.to_str().unwrap_or_default(),
            "/o",
        ])
        .output();

    match output {
        Ok(outp) => {
            if outp.status.success() {
                if out.exists() {
                    let _ = fs::remove_file(&out);
                }
                Ok(())
            } else {
                let stderr = String::from_utf8_lossy(&outp.stderr);
                let stdout = String::from_utf8_lossy(&outp.stdout);
                let combined = format!("{}\n{}", stderr, stdout);
                let first_error = combined
                    .lines()
                    .find(|l| l.contains("error") || l.contains("failed"))
                    .unwrap_or("MakeAppx pack failed");
                anyhow::bail!("{}", first_error.chars().take(120).collect::<String>());
            }
        }
        Err(e) => anyhow::bail!("MakeAppx exec failed: {}", e),
    }
}

fn prepare_makeappx_staging(example_dir: &Path) -> Result<()> {
    let assets_dir = example_dir.join("Assets");
    fs::create_dir_all(&assets_dir)?;

    for name in ["StoreLogo.png", "Square150x150Logo.png", "FileIcon.png"] {
        let path = assets_dir.join(name);
        if !path.exists() {
            fs::write(&path, minimal_png_bytes())?;
        }
    }

    if let Some(exe) = extract_manifest_executable(example_dir)? {
        if exe.contains("$(") || exe.contains('@') {
            return Ok(());
        }

        let exe_path = example_dir.join(exe.replace('\\', "/"));
        if let Some(parent) = exe_path.parent() {
            fs::create_dir_all(parent)?;
        }
        if !exe_path.exists() {
            fs::write(&exe_path, [])?;
        }
    }

    Ok(())
}

fn extract_manifest_executable(example_dir: &Path) -> Result<Option<String>> {
    let manifest = example_dir.join("AppxManifest.xml");
    if !manifest.exists() {
        return Ok(None);
    }

    let content = fs::read_to_string(&manifest)?;
    let mut reader = Reader::from_str(&content);
    reader.config_mut().trim_text(true);

    let mut buf = Vec::new();
    loop {
        match reader.read_event_into(&mut buf) {
            Ok(Event::Start(e)) | Ok(Event::Empty(e)) => {
                let qname = e.name();
                let name = qname.as_ref();
                let local_name = name.split(|b| *b == b':').next_back().unwrap_or(name);
                if local_name == b"Application" {
                    for attr in e.attributes().flatten() {
                        if attr.key.as_ref() == b"Executable" {
                            let value = attr.value.as_ref();
                            let exe = String::from_utf8_lossy(value).to_string();
                            return Ok(Some(exe));
                        }
                    }
                }
            }
            Ok(Event::Eof) => break,
            Err(e) => anyhow::bail!("invalid XML: {}", e),
            _ => {}
        }

        buf.clear();
    }

    Ok(None)
}

