use std::fs;

use options::GalleryOptions;

pub fn run_with_options(options: GalleryOptions) -> Result<()> {
    let paths = options.resolve_paths()?;

    if options.clean {
        for dir in dirs_to_clean(&options, &paths) {
            if dir.exists() {
                println!("Cleaning {}", dir.display());
                fs::remove_dir_all(dir)?;
            }
        }
    }

    let mut stats = Stats::default();

    if options.upgrade
        && (options.source_type == options::SourceType::Submodule
            || options.source_type == options::SourceType::All)
    {
        upgrade::run_upgrade(&options, &paths, &mut stats)?;
    }

    if options.build {
        build::run_build(&options, &paths, &mut stats)?;
    }

    if options.msix {
        msix::run_msix(&options, &paths, &mut stats)?;
    }

    let has_errors = stats.upgrade_errors > 0 || stats.build_errors > 0;
    if has_errors {
        anyhow::bail!("Completed with errors");
    }

    Ok(())
}

/// Output directories regenerated by the stages selected in `options`.
///
/// Only these are cleaned, so outputs of stages that are not run (and the
/// v4 upgrade results that build/msix read as input) are left intact.
fn dirs_to_clean<'a>(
    options: &GalleryOptions,
    paths: &'a options::ResolvedPaths,
) -> Vec<&'a std::path::Path> {
    let mut dirs = Vec::new();
    if options.upgrade {
        dirs.push(paths.v4_dir.as_path());
    }
    if options.build {
        dirs.push(paths.msi_dir.as_path());
    }
    if options.msix {
        dirs.push(paths.msix_dir.as_path());
        dirs.push(paths.msix_tmp_dir.as_path());
    }
    dirs
}

#[derive(Default)]
struct Stats {
    upgraded: usize,
    upgrade_errors: usize,
    built: usize,
    build_errors: usize,
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn options(upgrade: bool, build: bool, msix: bool) -> GalleryOptions {
        GalleryOptions {
            source_type: options::SourceType::All,
            source: PathBuf::from("src"),
            output: PathBuf::from("out"),
            configs: PathBuf::from("configs"),
            yaml_gallery: PathBuf::from("yaml"),
            clean: true,
            only_prefixes: None,
            upgrade,
            build,
            refresh: false,
            wixer: PathBuf::from("wixer"),
            verbose: false,
            validate: false,
            msix,
        }
    }

    fn dir_names(options: &GalleryOptions) -> Vec<String> {
        let paths = options.resolve_paths().unwrap();
        dirs_to_clean(options, &paths)
            .into_iter()
            .map(|d| d.file_name().unwrap().to_string_lossy().into_owned())
            .collect()
    }

    #[test]
    fn clean_with_build_only_keeps_v4_and_msix_outputs() {
        assert_eq!(dir_names(&options(false, true, false)), ["msi"]);
    }

    #[test]
    fn clean_with_msix_only_cleans_msix_dirs() {
        assert_eq!(
            dir_names(&options(false, false, true)),
            ["msix", ".msix-tmp"]
        );
    }

    #[test]
    fn clean_with_all_stages_cleans_all_outputs() {
        assert_eq!(
            dir_names(&options(true, true, true)),
            ["wix-v4", "msi", "msix", ".msix-tmp"]
        );
    }

    #[test]
    fn clean_without_stages_cleans_nothing() {
        let opts = options(false, false, false);
        let paths = opts.resolve_paths().unwrap();
        assert!(dirs_to_clean(&opts, &paths).is_empty());
    }
}
