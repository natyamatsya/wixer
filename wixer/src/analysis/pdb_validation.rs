//! PDB Validation - Compare compiled MSI against simulator expectations
//!
//! This module validates that the actual compiled WiX PDB matches what
//! the simulator expects, catching discrepancies like:
//! - Actions scheduled at unexpected positions
//! - Missing or extra custom actions
//! - Condition mismatches
//! - Sequence table discrepancies

use crate::simulation::{Action, Simulator};
use crate::wixpdb::{Symbol, WixPdb};
use std::collections::{HashMap, HashSet};

/// A discrepancy between expected (simulator) and actual (PDB) state
#[derive(Debug, Clone)]
pub struct ValidationWarning {
    pub kind: WarningKind,
    pub message: String,
    pub suggestion: Option<String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WarningKind {
    /// Action in simulator but not in PDB
    MissingAction,
    /// Action in PDB but not in simulator
    ExtraAction,
    /// Action exists but with different scheduling
    SchedulingMismatch,
    /// Action exists but with different condition
    ConditionMismatch,
    /// Action in wrong sequence table
    WrongSequenceTable,
    /// Custom action type mismatch
    TypeMismatch,
}

impl std::fmt::Display for WarningKind {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            WarningKind::MissingAction => write!(f, "Missing Action"),
            WarningKind::ExtraAction => write!(f, "Extra Action"),
            WarningKind::SchedulingMismatch => write!(f, "Scheduling Mismatch"),
            WarningKind::ConditionMismatch => write!(f, "Condition Mismatch"),
            WarningKind::WrongSequenceTable => write!(f, "Wrong Sequence Table"),
            WarningKind::TypeMismatch => write!(f, "Type Mismatch"),
        }
    }
}

/// Extracted action info from PDB
#[derive(Debug, Clone)]
struct PdbAction {
    name: String,
    action_type: String,
    sequence_table: Option<String>,
    sequence_number: Option<i64>,
    condition: Option<String>,
    before: Option<String>,
    after: Option<String>,
}

/// Validate a PDB against simulator expectations
pub fn validate(pdb: &WixPdb, simulator: &Simulator) -> Vec<ValidationWarning> {
    let mut warnings = Vec::new();

    // Extract actions from PDB
    let pdb_actions = extract_pdb_actions(pdb);
    let pdb_action_names: HashSet<String> = pdb_actions.keys().cloned().collect();

    // Get expected actions from simulator (custom actions + sequence actions)
    let custom_actions = simulator.get_custom_actions();
    let expected_action_ids: HashSet<String> =
        custom_actions.iter().map(|a| a.id.clone()).collect();

    // Check for missing actions (in simulator but not in PDB)
    for action in &custom_actions {
        if !pdb_action_names.contains(&action.id) {
            // Skip standard actions - they're implicit
            if !is_standard_action(&action.id) {
                warnings.push(ValidationWarning {
                    kind: WarningKind::MissingAction,
                    message: format!(
                        "Action '{}' defined in YAML but not found in compiled PDB",
                        action.id
                    ),
                    suggestion: Some(
                        "Check that the action is properly included in a Feature or referenced correctly".to_string()
                    ),
                });
            }
        }
    }

    // Check for extra actions (in PDB but not in simulator)
    for (name, pdb_action) in &pdb_actions {
        if !expected_action_ids.contains(name) && !is_standard_action(name) {
            // Check if it's from a WiX extension
            if is_extension_action(name) {
                continue; // Extension actions are expected to appear
            }

            warnings.push(ValidationWarning {
                kind: WarningKind::ExtraAction,
                message: format!(
                    "Action '{}' found in PDB but not defined in simulator (type: {})",
                    name, pdb_action.action_type
                ),
                suggestion: Some(
                    "This action may be auto-generated by WiX or an extension. If unexpected, check your WiX sources.".to_string()
                ),
            });
        }
    }

    // Check scheduling mismatches for actions that exist in both
    for action in &custom_actions {
        if let Some(pdb_action) = pdb_actions.get(&action.id) {
            // Check condition mismatch
            if let Some(expected_cond) = &action.condition
                && let Some(pdb_cond) = &pdb_action.condition
                && !conditions_equivalent(expected_cond, pdb_cond)
            {
                warnings.push(ValidationWarning {
                    kind: WarningKind::ConditionMismatch,
                    message: format!(
                        "Action '{}' has different condition. Expected: '{}', Got: '{}'",
                        action.id, expected_cond, pdb_cond
                    ),
                    suggestion: Some(
                        "Verify the condition expression in your YAML matches the compiled output"
                            .to_string(),
                    ),
                });
            }

            // Check scheduling (Before/After)
            check_scheduling_match(action, pdb_action, &mut warnings);
        }
    }

    warnings
}

fn extract_pdb_actions(pdb: &WixPdb) -> HashMap<String, PdbAction> {
    let mut actions = HashMap::new();

    for section in &pdb.sections {
        for symbol in &section.symbols {
            if let Some(action) = extract_action_from_symbol(symbol) {
                actions.insert(action.name.clone(), action);
            }
        }
    }

    actions
}

fn extract_action_from_symbol(symbol: &Symbol) -> Option<PdbAction> {
    match symbol.symbol_type.as_str() {
        "CustomAction" | "WixAction" => {
            let name = symbol
                .id
                .get("id")
                .and_then(|v| v.as_str())
                .or_else(|| symbol.id.as_str())?
                .to_string();

            let mut action = PdbAction {
                name,
                action_type: symbol.symbol_type.clone(),
                sequence_table: None,
                sequence_number: None,
                condition: None,
                before: None,
                after: None,
            };

            // Extract fields based on symbol type
            for field in &symbol.fields {
                if let Some(obj) = field.as_object() {
                    if let Some(seq) = obj.get("SequenceTable").and_then(|v| v.as_str()) {
                        action.sequence_table = Some(seq.to_string());
                    }
                    if let Some(num) = obj.get("Sequence").and_then(|v| v.as_i64()) {
                        action.sequence_number = Some(num);
                    }
                    if let Some(cond) = obj.get("Condition").and_then(|v| v.as_str()) {
                        action.condition = Some(cond.to_string());
                    }
                    if let Some(before) = obj.get("Before").and_then(|v| v.as_str()) {
                        action.before = Some(before.to_string());
                    }
                    if let Some(after) = obj.get("After").and_then(|v| v.as_str()) {
                        action.after = Some(after.to_string());
                    }
                }
            }

            Some(action)
        }
        _ => None,
    }
}

fn check_scheduling_match(
    expected: &Action,
    actual: &PdbAction,
    warnings: &mut Vec<ValidationWarning>,
) {
    use crate::simulation::SequencePosition;

    let Some(position) = &expected.position else {
        return;
    };

    match position {
        SequencePosition::Before(before_action) => {
            if actual.before.as_ref() != Some(before_action) {
                warnings.push(ValidationWarning {
                    kind: WarningKind::SchedulingMismatch,
                    message: format!(
                        "Action '{}' expected Before '{}', but PDB shows Before '{}'",
                        expected.id,
                        before_action,
                        actual.before.as_deref().unwrap_or("<none>")
                    ),
                    suggestion: None,
                });
            }
        }
        SequencePosition::After(after_action) => {
            if actual.after.as_ref() != Some(after_action) {
                warnings.push(ValidationWarning {
                    kind: WarningKind::SchedulingMismatch,
                    message: format!(
                        "Action '{}' expected After '{}', but PDB shows After '{}'",
                        expected.id,
                        after_action,
                        actual.after.as_deref().unwrap_or("<none>")
                    ),
                    suggestion: None,
                });
            }
        }
        _ => {}
    }
}

